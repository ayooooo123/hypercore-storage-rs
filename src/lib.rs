/// Anything a store operation can fail with.
#[derive(Debug)]
pub enum Error {
    /// RocksDB refused the open, read or write.
    Rocks(String),
    /// A stored row did not decode.
    Codec(String),
    Io(std::io::Error),
    /// The store was closed.
    Closed,
    /// The store was opened read-only.
    ReadOnly,
    /// A row exists but does not hold what the layout expects.
    Corrupt(String),
    /// The caller asked for something impossible.
    BadArgument(String),
}

impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Rocks(e) => write!(f, "rocksdb: {e}"),
            Self::Codec(e) => write!(f, "decode: {e}"),
            Self::Io(e) => write!(f, "io: {e}"),
            Self::Closed => f.write_str("store closed"),
            Self::ReadOnly => f.write_str("store is read-only"),
            Self::Corrupt(e) => write!(f, "corrupt store: {e}"),
            Self::BadArgument(e) => write!(f, "bad argument: {e}"),
        }
    }
}

impl std::error::Error for Error {}

pub type Result<T, E = Error> = std::result::Result<T, E>;

impl From<compact_encoding::Error> for Error {
    fn from(e: compact_encoding::Error) -> Self {
        Self::Codec(format!("{e}"))
    }
}

impl From<std::io::Error> for Error {
    fn from(e: std::io::Error) -> Self {
        Self::Io(e)
    }
}
