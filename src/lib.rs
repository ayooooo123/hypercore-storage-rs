//! A Rust port of npm `hypercore-storage` 3.4.0: the same RocksDB directory,
//! read and written.
//!
//! A store written by corestore 7.16.1 + hypercore 11.40.3 opens here and the
//! reverse, so the JS and Rust stacks can take turns on one directory. The row
//! layout is documented in `docs/format.md`; the keys are `index-encoder`
//! values, the values are hyperschema encodings from hypercore-storage's own
//! `schema.json`.
//!
//! ```ignore
//! use hypercore_storage::{Store, CreateCore};
//!
//! let store = Store::open(std::path::Path::new("./db"))?;
//! let core = store.create_core(CreateCore { key, discovery_key, ..Default::default() })?;
//! let mut tx = core.write();
//! tx.put_block(0, bytes::Bytes::from_static(b"hello"));
//! core.flush(tx)?;
//! # Ok::<(), hypercore_storage::Error>(())
//! ```

#![forbid(unsafe_code)]

