mod tree_cache;

/// Codecs generated by `hyperschema-rs` from hypercore-storage's `schema.json`.
mod encoding {
    #![allow(dead_code)]
    include!(concat!(env!("OUT_DIR"), "/hypercore_storage.rs"));
}

pub mod flat;
